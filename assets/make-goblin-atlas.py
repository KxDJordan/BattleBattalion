#!/usr/bin/env python3
"""Cut the user's goblin sheets into their drawn frames and pack them.

  python3 -I assets/make-goblin-atlas.py

Reads (all frames facing right, the front three-quarter view)
  assets/foes/goblin-skirmisher.webp  five rows of six: 1 idle, 2 run, 3 attack, 4 hit, 5 death (knife in the near hand, a round shield)
  assets/foes/goblin-archer.webp      six rows of eight: 1 idle, 2 walk / run, 3 attack (draw and loose), 4 cast (the purple glow),
                                      5 hit, 6 death (bow and quiver)
  assets/foes/goblin-shaman.webp      the same rows (skull staff): the attack a staff swing with a swoosh arc, the cast a purple glow
                                      gathering in the hand, then on the staff's skull; two attack frames touch (split along a seam)
Writes src/76f-gobatlas.js: GBA (skirmisher), GAA (archer) and GSA (shaman), each sheet's frames packed as a half-size webp data URL with each
frame's anchor (read by 76g-frames.js). A frame is its figure plus any loose bits in its cell (the cast's glow, wisps).
Units: each sheet's px. Each frame's anchor is the body's centre (median x of its opaque pixels) over its feet (its lowest opaque
row; a run frame with both feet off the ground uses the row's ground line). GBA.H: the first idle frame's height.
No randomness: the output is the same every run.
"""
import json, os, sys
import numpy as np
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import foeframes as ff

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
K_GAME = 0.5
SHEETS = [('GBA', 'goblin-skirmisher.webp', 'GOBLIN SKIRMISHER', [('idle', 0, 300), ('run', 300, 580), ('attack', 580, 850), ('hit', 850, 1130), ('death', 1130, 1500)], 6),
          ('GAA', 'goblin-archer.webp', 'GOBLIN ARCHER', [('idle', 0, 180), ('run', 180, 365), ('attack', 365, 550), ('cast', 550, 735), ('hit', 735, 920), ('death', 920, 1125)], 8),
          ('GSA', 'goblin-shaman.webp', 'GOBLIN SHAMAN', [('idle', 0, 185), ('run', 185, 365), ('attack', 365, 550), ('cast', 550, 735), ('hit', 735, 925), ('death', 925, 1125)], 8)]
JS = ['/* ================= GOBLIN FRAMES (generated by assets/make-goblin-atlas.py from assets/foes/goblin-skirmisher.webp, goblin-archer.webp and goblin-shaman.webp; do not edit) =================\n'
      '   GBA (the skirmisher) / GAA (the archer) / GSA (the shaman): .f[anim] = the drawn frames, each {r: [x,y,w,h] in the atlas (px of this half-size webp), w h: the\n'
      '   frame in sheet px, ax ay: the body\'s centre over the feet, frame px}, facing right; .H: the first idle frame\'s height. */\n']
for var, fn, title, ROWS, N in SHEETS:
    A, b64, nbytes = ff.frame_sheet(os.path.join(ROOT, 'assets', 'foes', fn), ROWS, N, K_GAME)
    JS.append('const %s=%s;\n%s.src=\'data:image/webp;base64,%s\';\n' % (var, json.dumps(A, separators=(',', ':')), var, b64))
    print('%s atlas %dx%d, webp %d KB, H %.0f' % (title, A['w'] * 2, A['h'] * 2, nbytes // 1024, A['H']))
with open(os.path.join(ROOT, 'src', '76f-gobatlas.js'), 'w') as f:
    f.write(''.join(JS))
