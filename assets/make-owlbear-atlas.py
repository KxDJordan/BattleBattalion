#!/usr/bin/env python3
"""Cut the user's Owlbear sheet into its drawn frames and pack them.

  python3 -I assets/make-owlbear-atlas.py

Reads assets/foes/owlbear.webp: six rows of eight frames, all facing right (the front three-quarter view): 1 idle, 2 walk / run,
3 attack (a claw swipe with a swoosh arc), 4 cast (a purple glow gathering in the claws, then purple arcs), 5 hit, 6 death.
Many neighbouring frames touch: they are split along least-alpha seams at the cell grid (assets/foeframes.py frame_sheet).
Writes src/76i-owlatlas.js: OBA, the frames packed as a half-size webp data URL with each frame's anchor (the body's centre over
the feet; read by 76g-frames.js). Units: the sheet's px. No randomness: the output is the same every run.
"""
import json, os, sys
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import foeframes as ff

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROWS = [('idle', 0, 185), ('run', 185, 365), ('attack', 365, 550), ('cast', 550, 735), ('hit', 735, 925), ('death', 925, 1125)]
A, b64, nbytes = ff.frame_sheet(os.path.join(ROOT, 'assets', 'foes', 'owlbear.webp'), ROWS, 8, 0.5, loose={'attack': [(565, 8)]})   # frame 5's swoosh touches frame 6
js = ('/* ================= OWLBEAR FRAMES (generated by assets/make-owlbear-atlas.py from assets/foes/owlbear.webp; do not edit) =================\n'
      '   OBA.f[anim] = the drawn frames, each {r: [x,y,w,h] in the atlas (px of this half-size webp), w h: the frame in sheet px, ax ay: the\n'
      '   body\'s centre over the feet, frame px}, facing right: idle, run, attack, cast, hit, death (8 each). OBA.H: the first idle frame\'s height. */\n'
      'const OBA=%s;\nOBA.src=\'data:image/webp;base64,%s\';\n' % (json.dumps(A, separators=(',', ':')), b64))
with open(os.path.join(ROOT, 'src', '76i-owlatlas.js'), 'w') as f:
    f.write(js)
print('OWLBEAR atlas %dx%d, webp %d KB, H %.0f' % (A['w'] * 2, A['h'] * 2, nbytes // 1024, A['H']))
